#!/usr/bin/env bash
set -euo pipefail

out="${1:-reports/tools_report.md}"
mkdir -p "$(dirname "$out")"

check_cmd() {
  local name="$1"
  local path
  if path="$(command -v "$name" 2>/dev/null)"; then
    printf '| `%s` | OK | `%s` |\n' "$name" "$path"
  else
    printf '| `%s` | MISSING |  |\n' "$name"
  fi
}

section() {
  local title="$1"
  shift
  {
    printf '\n## %s\n\n' "$title"
    printf '| Tool | Status | Path |\n'
    printf '|---|---|---|\n'
    for tool in "$@"; do
      check_cmd "$tool"
    done
  } >> "$out"
}

cat > "$out" <<'EOF'
# CTF Tools Report

Generated by `scripts/check_ctf_tools.sh`.

EOF

section "Core / Archive / Encoding" \
  file strings xxd hexdump base64 openssl jq yq unzip 7z tar gzip bzip2 xz zstd \
  python3 ruby go cargo node npm

section "Misc / Stego / Media" \
  binwalk foremost exiftool steghide zsteg pngcheck identify convert ffmpeg \
  stegseek outguess sonic-visualiser

section "Web / Network" \
  curl wget nc ncat socat nmap masscan ffuf feroxbuster gobuster dirsearch sqlmap \
  httpx nuclei nikto whatweb wafw00f arjun xsser dalfox amass subfinder dnsx \
  tshark tcpdump wireshark editcap mergecap

section "Pwn / Reverse" \
  gdb gdbserver checksec objdump readelf nm ldd patchelf strace ltrace radare2 r2 \
  rizin rz-bin ghidra analyzeHeadless jadx jadx-gui apktool java ROPgadget ropper \
  one_gadget seccomp-tools qemu-x86_64 qemu-i386

section "Math / Algebra" \
  sage sage-python

section "Forensics" \
  vol volatility3 vol.py bulk_extractor foremost scalpel fls icat mmls fsstat \
  photorec testdisk yara yarac

printf 'Wrote %s\n' "$out"
